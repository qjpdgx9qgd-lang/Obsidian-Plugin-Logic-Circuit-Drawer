import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { licenseNotices } from './scripts/license-notices.mjs';
import { assertNoRuntimeScripts, noRuntimeScripts } from './scripts/no-runtime-scripts.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	metafile: true,
	outfile: 'main.js',
	minify: prod,
	define: { 'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development') },
	plugins: [noRuntimeScripts(), {
		name: 'plugin-styles',
		setup(build) {
			// Track custom CSS in watch mode; Obsidian loads the combined stylesheet.
			build.onLoad({ filter: /src\/ui\/styles\.css$/ }, args => ({
				contents: '', loader: 'js', watchFiles: [args.path, 'LICENSE', 'licenses/obsidian-sample-plugin-0BSD.txt'],
			}));
			build.onEnd(async result => {
				if (result.errors.length) return;
				const [base, custom] = await Promise.all([
					readFile('node_modules/@xyflow/react/dist/style.css', 'utf8'),
					readFile('src/ui/styles.css', 'utf8'),
				]);
				await writeFile('styles.css', `${base}\n${custom}`);
				const notices = await licenseNotices(result.metafile);
				await writeFile('THIRD-PARTY-NOTICES.txt', notices);
				// Community-plugin installation downloads main.js, manifest and CSS.
				// Embed the complete notices so they travel with that minimal install.
				const [javascript, license] = await Promise.all([readFile('main.js', 'utf8'), readFile('LICENSE', 'utf8')]);
				assertNoRuntimeScripts(javascript);
				await writeFile('main.js', `${javascript}\n/*\n${(license + '\n' + notices).replace(/\*\//g, '* /')}*/\n`);
			});
		},
	}],
});

if (prod) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
